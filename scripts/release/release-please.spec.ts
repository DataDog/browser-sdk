import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
// Not part of release-please's public API: used to check the notes format the pre-tag check relies on.
import { DefaultChangelogNotes } from 'release-please/build/src/changelog-notes/default.js'
import type { ConventionalCommit } from 'release-please'
import { findMissingCommits, getVisibleTypes } from './release-please.ts'
import type { GitCommit } from './release-please.ts'

const VISIBLE_TYPES = getVisibleTypes()
const FEAT_COMMIT: GitCommit = { sha: 'a'.repeat(40), subject: 'feat(rum): Add view name API (#5300)' }
const FIX_COMMIT: GitCommit = { sha: 'b'.repeat(40), subject: 'fix(logs): Drop empty context (#5301)' }

function buildNotes(commits: GitCommit[]): Promise<string> {
  const conventionalCommits = commits.map(({ sha, subject }): ConventionalCommit => {
    const [, type, scope, bareMessage] = /^(\w+)\((.+?)\): (.*)$/.exec(subject)!
    return { sha, message: subject, files: [], type, scope, bareMessage, notes: [], references: [], breaking: false }
  })
  return new DefaultChangelogNotes().buildNotes(conventionalCommits, {
    owner: 'DataDog',
    repository: 'browser-sdk',
    version: '7.18.0',
    previousTag: 'v7.17.1',
    currentTag: 'v7.18.0',
    targetBranch: 'main',
    changelogSections: [
      { type: 'feat', section: 'Features' },
      { type: 'fix', section: 'Bug Fixes' },
    ],
  })
}

describe('getVisibleTypes', () => {
  it('returns the types of visible changelog sections', () => {
    assert.equal(VISIBLE_TYPES.has('feat'), true)
    assert.equal(VISIBLE_TYPES.has('chore'), true)
    assert.equal(VISIBLE_TYPES.has('staging'), false)
  })
})

describe('findMissingCommits', () => {
  it('accepts release notes generated by release-please for every commit', async () => {
    const commits = [FEAT_COMMIT, FIX_COMMIT]
    assert.deepEqual(findMissingCommits(await buildNotes(commits), commits, VISIBLE_TYPES), [])
  })

  it('reports commits that are not in the release notes', async () => {
    const notes = await buildNotes([FEAT_COMMIT])
    assert.deepEqual(findMissingCommits(notes, [FEAT_COMMIT, FIX_COMMIT], VISIBLE_TYPES), [FIX_COMMIT])
  })

  it('ignores commits that never get a changelog entry', () => {
    const commits = [
      { sha: 'c'.repeat(40), subject: '✨ [RUM-123] Legacy gitmoji title (#5200)' },
      { sha: 'd'.repeat(40), subject: 'staging(ci): Bump staging to staging-47' },
      { sha: 'e'.repeat(40), subject: 'v7.17.1 (#5256)' },
    ]
    assert.deepEqual(findMissingCommits('', commits, VISIBLE_TYPES), [])
  })
})
