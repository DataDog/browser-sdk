import { readFileSync } from 'node:fs'
import jsCorePackageJson from '../../packages/js-core/package.json' with { type: 'json' }
import { releaseVersion } from '../lib/browserSdkVersion.ts'
import { createGitHubRelease, findGitHubRelease, publishGitHubRelease } from '../lib/gitUtils.ts'
import { printLog, runMain } from '../lib/executionUtils.ts'

if (!process.env.NODE_TEST_CONTEXT) {
  runMain(() => main())
}

/**
 * Publish the GitHub releases of the version being deployed. release-please creates them as drafts
 * when the release pull request is merged, so they only become public once the deployment is done.
 */
export async function main({ changelogPath = 'CHANGELOG.md' } = {}): Promise<void> {
  // Publish js-core first, so the Browser SDK release ends up marked as the latest one.
  await publishDraftRelease(`js-core-v${jsCorePackageJson.version}`, { makeLatest: false })

  const sdkTag = `v${releaseVersion}`
  if (!(await publishDraftRelease(sdkTag, { makeLatest: true }))) {
    // TODO: remove once releases are created by release-please.
    printLog(`Creating GitHub release ${sdkTag} from ${changelogPath}`)
    const body = getReleaseBodyFromChangelog(readFileSync(changelogPath, 'utf8'), sdkTag)
    const release = await createGitHubRelease({ version: sdkTag, body })
    printLog(`GitHub release created: ${release.html_url}`)
  }
}

/**
 * Publish the draft GitHub release of the given tag.
 *
 * @returns Whether a release exists for this tag, published or not.
 */
async function publishDraftRelease(tag: string, { makeLatest }: { makeLatest: boolean }): Promise<boolean> {
  const release = await findGitHubRelease(tag)
  if (!release) {
    printLog(`No GitHub release found for ${tag}`)
    return false
  }

  if (!release.draft) {
    printLog(`GitHub release ${tag} is already published: ${release.html_url}`)
    return true
  }

  const publishedRelease = await publishGitHubRelease(release.id, { makeLatest })
  printLog(`GitHub release published: ${publishedRelease.html_url}`)
  return true
}

/**
 * Get the body of a release from a CHANGELOG.md generated by the legacy release script.
 */
export function getReleaseBodyFromChangelog(changelog: string, tag: string): string {
  const titleMatches = [...changelog.matchAll(/^## (v\d+\.\d+\.\d+)/gm)]
  const index = titleMatches.findIndex((match) => match[1] === tag)
  if (index === -1) {
    throw new Error(`No release ${tag} found in CHANGELOG.md`)
  }

  const titleMatch = titleMatches[index]
  return changelog.slice(titleMatch.index + titleMatch[0].length, titleMatches[index + 1]?.index).trim()
}
